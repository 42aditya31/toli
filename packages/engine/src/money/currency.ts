const TABLE = new Map<string, number>();
for (const c of EXPONENT_2) TABLE.set(c, 2);
for (const c of EXPONENT_0) TABLE.set(c, 0);
for (const c of EXPONENT_3) TABLE.set(c, 3);
for (const c of EXPONENT_4) TABLE.set(c, 4);

export const SUPPORTED_CURRENCIES: readonly string[] = [
  'INR',
  ...[...TABLE.keys()].filter((c) => c !== 'INR').sort(),
];

export function currencyExponent(code: string): number {
  const e = TABLE.get(code);
  if (e === undefined) throw new Error(`unknown_currency: ${code}`);
  return e;
}

export function pow10(e: number): bigint {
  return 10n ** BigInt(e);
}
